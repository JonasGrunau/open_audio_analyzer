/// The conformance suite for `packages/oaa_ui/lib/src/qr.dart`.
///
/// **A QR encoder that has never been read by a scanner is a picture
/// generator.** The failure this exists to make impossible is the one with no
/// symptom: a wrong mask, a transposed format field or an off-by-one in the
/// interleave each produce something that looks exactly like a QR code, that
/// passes every widget test anybody would think to write, and that no camera
/// will read. On screen it is indistinguishable from a dirty lens or a bad
/// angle, so it reaches a user as "scanning does not work on my machine".
///
/// Three things hold it, in descending order of how much they prove.
///
/// **1. Every fixture below was read by both decoders that will ever see one.**
/// `mobile_scanner` is ML Kit on Android, which is ZXing, and Apple's Vision
/// framework on iOS and macOS — so these are the actual consumers answering,
/// not a second encoder's opinion. All fifteen round-trip through both.
/// Reproduce by rendering a fixture at eight pixels per module with four
/// modules of white border and then, for ZXing:
///
/// ```py
/// # pip install zxing-cpp pillow
/// import zxingcpp
/// assert zxingcpp.read_barcode(img).text == text
/// ```
///
/// and for Vision, a `swift` script with `VNDetectBarcodesRequest`, its
/// `symbologies` set to `[.qr]`, reading `payloadStringValue` off the first
/// `VNBarcodeObservation`. Neither needs a camera or any permission.
///
/// **2. [_read] takes the symbol apart the way a scanner does** — format field,
/// mask, unmask, zigzag, mode, count, bytes — and every case round-trips
/// through it. That check needs no fixture at all, so it survives a
/// regeneration: a change that broke placement and updated the goldens to
/// match would still fail here.
///
/// **3. The chosen version is checked against the published capacity table.**
/// A capacity table one codeword out picks a symbol larger than it needs —
/// which still scans, and then silently refuses the one input that needed the
/// version above it.
///
/// What is deliberately *not* here is equality with another encoder's matrix.
/// Two were tried. segno pads a byte-mode stream that already ends on a
/// codeword boundary with a spurious zero codeword, which is every byte-mode
/// symbol with room to pad; the `qrcode` package agrees with this encoder about
/// padding and disagrees about masks. All three produce symbols ZXing reads,
/// because mask selection is a quality heuristic and a decoder reads whichever
/// mask the format field names. Holding this file to either one's matrix would
/// be recording somebody else's tie-break as though it were the specification.
///
/// The first five cases are the payloads the application really encodes. The
/// ten after them each sit on the exact byte capacity of one version, so the
/// suite covers every version this encoder builds and, with them, both
/// character-count widths, all four block structures, the alignment grid, and
/// the version block that appears at version 7.
void main() {
  group('encoding', () {
    for (final (text, expected) in _cases) {
      test('${text.length} bytes are the symbol both decoders read', () {
        final code = QrCode.encode(text);

        expect(code, isNotNull, reason: 'did not fit in any version');
        expect(code!.size, expected.length);
        expect(_render(code), expected);
      });

      test('${text.length} bytes read back off the symbol', () {
        expect(_read(QrCode.encode(text)!), text);
      });
    }

    // The published byte-mode capacities at error level M, which is what this
    // encoder's two ten-entry tables have to reproduce between them.
    test('each version is chosen at its published capacity', () {
      const capacities = [14, 26, 42, 62, 84, 106, 122, 152, 180, 213];
      for (final (index, capacity) in capacities.indexed) {
        expect(QrCode.encode('x' * capacity)!.version, index + 1);
        // One byte over, and the symbol has to grow — except past the last
        // version, where it has nowhere to grow to.
        expect(
          QrCode.encode('x' * (capacity + 1))?.version,
          index + 1 < capacities.length ? index + 2 : isNull,
        );
      }
    });

    test('more than version 10 can hold does not fit', () {
      expect(QrCode.encode('x' * 213), isNotNull);
      expect(QrCode.encode('x' * 214), isNull);
    });

    // Not a capacity check — a check that the payload goes out in byte mode.
    // The same string in alphanumeric mode fits a smaller symbol, and a
    // decoder reading `oaa://host` out of an alphanumeric segment gets back
    // `OAA://HOST`: an address that resolves to nothing, produced by a code
    // that scanned perfectly.
    test('an address keeps its case', () {
      expect(
        _read(QrCode.encode('oaa://studio-mac.local:5555')!),
        'oaa://studio-mac.local:5555',
      );
    });
  });

  group('painting', () {
    // The quiet zone is part of the symbol. A code drawn edge to edge against a
    // panel is a code whose three finder patterns run into the border, and the
    // locator cannot separate them from it.
    testWidgets('the code is drawn inside its quiet zone', (tester) async {
      await tester.pumpWidget(
        Center(child: OaaQrCode(code: QrCode.encode('oaa://1.2.3.4:5555')!)),
      );

      expect(tester.getSize(find.byType(OaaQrCode)), const Size(220, 220));
    });
  });
}

List<String> _render(QrCode code) => [
  for (var y = 0; y < code.size; y++)
    [for (var x = 0; x < code.size; x++) code.isDark(x, y) ? '#' : '.'].join(),
];

/// Reads a symbol the way a scanner does, and returns what it says.
///
/// Deliberately written against the *format field* rather than against the
/// encoder's chosen mask, so it agrees with the symbol only if the symbol says
/// what it wears. Everything a decoder does after this — Reed–Solomon
/// correction — is skipped, because the codewords are undamaged; what is being
/// checked is that the payload is where the specification says to look.
String _read(QrCode code) {
  final size = code.size;
  final version = code.version;
  final reserved = _reserved(size, version);

  var format = 0;
  for (var i = 0; i <= 5; i++) {
    if (code.isDark(8, i)) format |= 1 << i;
  }
  if (code.isDark(8, 7)) format |= 1 << 6;
  if (code.isDark(8, 8)) format |= 1 << 7;
  if (code.isDark(7, 8)) format |= 1 << 8;
  for (var i = 9; i < 15; i++) {
    if (code.isDark(14 - i, 8)) format |= 1 << i;
  }

  var mask = -1;
  for (var candidate = 0; candidate < 8; candidate++) {
    var remainder = candidate;
    for (var i = 0; i < 10; i++) {
      remainder = (remainder << 1) ^ ((remainder >> 9) * 0x537);
    }
    if (((candidate << 10 | remainder) ^ 0x5412) == format) mask = candidate;
  }
  expect(mask, isNot(-1), reason: 'the format field is not level M');

  final bits = <int>[];
  for (var right = size - 1; right >= 1; right -= 2) {
    if (right == 6) right = 5;
    for (var vertical = 0; vertical < size; vertical++) {
      for (var j = 0; j < 2; j++) {
        final x = right - j;
        final y = ((right + 1) & 2) == 0 ? size - 1 - vertical : vertical;
        if (reserved[y * size + x] != 0) continue;
        final invert = switch (mask) {
          0 => (x + y) % 2 == 0,
          1 => y % 2 == 0,
          2 => x % 3 == 0,
          3 => (x + y) % 3 == 0,
          4 => (y ~/ 2 + x ~/ 3) % 2 == 0,
          5 => x * y % 2 + x * y % 3 == 0,
          6 => (x * y % 2 + x * y % 3) % 2 == 0,
          _ => ((x + y) % 2 + x * y % 3) % 2 == 0,
        };
        bits.add((code.isDark(x, y) ? 1 : 0) ^ (invert ? 1 : 0));
      }
    }
  }

  // De-interleave. The codewords come off the symbol one per block in turn,
  // so on any version above 3 the payload is not contiguous — reading the bit
  // stream straight through gets the first codeword of every block and then
  // gibberish. The two tables are the published ones, written out here rather
  // than imported, so that a typo in the encoder's copy of them fails this.
  const eccPerBlock = [10, 16, 26, 18, 24, 16, 18, 22, 22, 26];
  const blockCount = [1, 1, 1, 2, 2, 4, 4, 4, 5, 5];
  final blocks = blockCount[version - 1];
  final eccLength = eccPerBlock[version - 1];
  final raw = bits.length ~/ 8;
  final shortBlocks = blocks - raw % blocks;
  final shortLength = raw ~/ blocks;

  final grouped = [for (var j = 0; j < blocks; j++) <int>[]];
  for (var i = 0, read = 0; i <= shortLength; i++) {
    for (var j = 0; j < blocks; j++) {
      if (i == shortLength - eccLength && j < shortBlocks) continue;
      if (read >= raw) break;
      grouped[j].add(
        [
          for (var b = 0; b < 8; b++) bits[read * 8 + b],
        ].fold(0, (value, bit) => value << 1 | bit),
      );
      read++;
    }
  }

  final data = [
    for (var j = 0; j < blocks; j++)
      ...grouped[j].take(shortLength - eccLength + (j < shortBlocks ? 0 : 1)),
  ];

  var cursor = 0;
  int take(int width) {
    var value = 0;
    for (var i = 0; i < width; i++) {
      value = value << 1 | (data[cursor >> 3] >> (7 - (cursor & 7))) & 1;
      cursor++;
    }
    return value;
  }

  expect(take(4), 0x4, reason: 'not byte mode');
  final length = take(version < 10 ? 8 : 16);
  return String.fromCharCodes([for (var i = 0; i < length; i++) take(8)]);
}

/// The modules a decoder skips: everything that is not payload.
Uint8List _reserved(int size, int version) {
  final reserved = Uint8List(size * size);
  void mark(int x, int y) {
    if (x >= 0 && x < size && y >= 0 && y < size) reserved[y * size + x] = 1;
  }

  for (var i = 0; i < size; i++) {
    mark(6, i);
    mark(i, 6);
  }
  for (final (cx, cy) in [(3, 3), (size - 4, 3), (3, size - 4)]) {
    for (var dy = -4; dy <= 4; dy++) {
      for (var dx = -4; dx <= 4; dx++) {
        mark(cx + dx, cy + dy);
      }
    }
  }
  if (version > 1) {
    final count = version ~/ 7 + 2;
    final step = (version * 4 + count * 2 + 1) ~/ (count * 2 - 2) * 2;
    final positions = List<int>.filled(count, 6);
    for (var i = count - 1, pos = version * 4 + 10; i >= 1; i--, pos -= step) {
      positions[i] = pos;
    }
    for (var i = 0; i < count; i++) {
      for (var j = 0; j < count; j++) {
        final corner =
            (i == 0 && j == 0) ||
            (i == 0 && j == count - 1) ||
            (i == count - 1 && j == 0);
        if (corner) continue;
        for (var dy = -2; dy <= 2; dy++) {
          for (var dx = -2; dx <= 2; dx++) {
            mark(positions[i] + dx, positions[j] + dy);
          }
        }
      }
    }
  }
  for (var i = 0; i < 6; i++) {
    mark(8, i);
  }
  mark(8, 7);
  mark(8, 8);
  mark(7, 8);
  for (var i = 9; i < 15; i++) {
    mark(14 - i, 8);
  }
  for (var i = 0; i < 8; i++) {
    mark(size - 1 - i, 8);
  }
  for (var i = 8; i < 15; i++) {
    mark(8, size - 15 + i);
  }
  mark(8, size - 8);
  if (version >= 7) {
    for (var i = 0; i < 18; i++) {
      mark(size - 11 + i % 3, i ~/ 3);
      mark(i ~/ 3, size - 11 + i % 3);
    }
  }
  return reserved;
}

